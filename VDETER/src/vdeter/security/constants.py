"""VDS2 wire sizes and deployment usage limits."""

SECURITY_CONTROL = 0x80
AAD_DOMAIN = b"VDS2"
KEY_BYTES = 32
NONCE_PREFIX_BYTES = 8
COUNTER_BYTES = 4
NONCE_BYTES = 12
HEADER_BYTES = 7
TAG_BYTES = 16
AAD_BYTES = 22
PDU_OVERHEAD = HEADER_BYTES + TAG_BYTES
REPLAY_WINDOW = 64
TX_BLOCK_SIZE = 1024
MAX_COUNTER = 1 << 24
MAX_GCM_BLOCKS = 1 << 32
MAX_AUTH_FAILURES = 1 << 20
MAX_AUTH_BLOCKS_PER_MESSAGE = 14

assert NONCE_PREFIX_BYTES + COUNTER_BYTES == NONCE_BYTES
assert len(AAD_DOMAIN) + 3 + 4 + 4 + HEADER_BYTES == AAD_BYTES
assert PDU_OVERHEAD == 23
